def setup_styles(doc: Document) -> None:
    normal = doc.styles["Normal"]
    normal.font.name = FONT
    normal.font.size = Pt(14)
    normal._element.rPr.rFonts.set(qn("w:eastAsia"), FONT)
    pf = normal.paragraph_format
    pf.line_spacing = 1.5
    pf.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    pf.first_line_indent = Cm(1.25)
    pf.space_after = Pt(0)

    for i, size in ((1, 16), (2, 14), (3, 14)):
        st = doc.styles[f"Heading {i}"]
        st.font.name = FONT
        st.font.size = Pt(size)
        st.font.bold = True
        st.font.color.rgb = RGBColor(0, 0, 0)
        st.paragraph_format.line_spacing = 1.5
        st.paragraph_format.space_before = Pt(12)
        st.paragraph_format.space_after = Pt(6)
        st.paragraph_format.first_line_indent = Cm(0)
        st.paragraph_format.keep_with_next = True

    sec = doc.sections[0]
    sec.left_margin, sec.right_margin = Cm(3), Cm(1.5)
    sec.top_margin, sec.bottom_margin = Cm(2), Cm(2)


def add_page_numbers(doc: Document) -> None:
    """Нумерация страниц по центру нижнего колонтитула; на титульном листе
    номер не отображается (different first page), нумерация видна со 2-й стр."""
    sec0 = doc.sections[0]
    sec0.different_first_page_header_footer = True
    p = sec0.footer.paragraphs[0]
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.first_line_indent = Cm(0)
    run = p.add_run()
    for kind, txt in (("begin", None), (None, "PAGE"), ("end", None)):
        if kind:
            fld = OxmlElement("w:fldChar")
            fld.set(qn("w:fldCharType"), kind)
            run._r.append(fld)
        else:
            instr = OxmlElement("w:instrText")
            instr.set(qn("xml:space"), "preserve")
            instr.text = txt
            run._r.append(instr)
    run.font.name = FONT
    run.font.size = Pt(12)
    # последующие секции (приложения) наследуют колонтитул первой секции
    for section in doc.sections[1:]:
        section.footer.is_linked_to_previous = True


def h(doc, text, level=1):
    return doc.add_heading(text, level=level)


def para(doc, text, *, indent=True, align=WD_ALIGN_PARAGRAPH.JUSTIFY, bold=False):
    p = doc.add_paragraph()
    p.alignment = align
    if not indent:
        p.paragraph_format.first_line_indent = Cm(0)
    r = p.add_run(text)
    r.bold = bold
    return p


def paras(doc, *chunks):
    for c in chunks:
        para(doc, c)


def bullets(doc, items, numbered=False):
    style = "List Number" if numbered else "List Bullet"
    for it in items:
        p = doc.add_paragraph(it, style=style)
        p.paragraph_format.first_line_indent = Cm(0)
        p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY


def caption(doc, text, *, size=12):
    p = doc.add_paragraph(text)
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.first_line_indent = Cm(0)
    p.paragraph_format.keep_together = True
    p.runs[0].italic = True
    p.runs[0].font.size = Pt(size)


def figure(doc, name, cap, width_cm=16.5):
    path = FIGURES_DIR / f"{name}.png"
    if not path.exists():
        log.warning("нет рисунка %s — пропущен", path.name)
        return
    N["fig"] += 1
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.first_line_indent = Cm(0)
    p.add_run().add_picture(str(path), width=Cm(width_cm))
    caption(doc, f"Рисунок {N['fig']} — {cap}")


def table(doc, title, headers, rows, *, widths=None, body_pt=11):
    N["tab"] += 1
    cap = doc.add_paragraph(f"Таблица {N['tab']} — {title}")
    cap.alignment = WD_ALIGN_PARAGRAPH.LEFT
    cap.paragraph_format.first_line_indent = Cm(0)
    cap.paragraph_format.keep_with_next = True
    cap.runs[0].font.size = Pt(12)

    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_ALIGN_PARAGRAPH.CENTER
    for j, htext in enumerate(headers):
        c = t.rows[0].cells[j]
        c.text = str(htext)
        c.paragraphs[0].runs[0].bold = True
        c.paragraphs[0].runs[0].font.size = Pt(body_pt)
        c.paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
    for row in rows:
        cells = t.add_row().cells
        for j, val in enumerate(row):
            cells[j].text = "" if val is None else str(val)
            for pr in cells[j].paragraphs:
                pr.paragraph_format.first_line_indent = Cm(0)
                pr.paragraph_format.line_spacing = 1.0
                pr.paragraph_format.space_after = Pt(0)
                for rn in pr.runs:
                    rn.font.size = Pt(body_pt)
    if widths:
        for j, w in enumerate(widths):
            for r in t.rows:
                r.cells[j].width = Cm(w)
    doc.add_paragraph().paragraph_format.first_line_indent = Cm(0)
    return t


def listing(doc, title, code, *, size=8.5):
    N["lst"] += 1
    cap = doc.add_paragraph(f"Листинг {N['lst']} — {title}")
    cap.alignment = WD_ALIGN_PARAGRAPH.LEFT
    cap.paragraph_format.first_line_indent = Cm(0)
    cap.paragraph_format.keep_with_next = True
    cap.runs[0].font.size = Pt(12)

    t = doc.add_table(rows=1, cols=1)
    t.style = "Table Grid"
    cell = t.rows[0].cells[0]
    lines = code.rstrip().split("\n")
    for i, line in enumerate(lines):
        p = cell.paragraphs[0] if i == 0 else cell.add_paragraph()
        p.paragraph_format.first_line_indent = Cm(0)
        p.paragraph_format.line_spacing = 1.0
        p.paragraph_format.space_after = Pt(0)
        r = p.add_run(line if line.strip() else " ")
        r.font.name = MONO
        r._element.rPr.rFonts.set(qn("w:eastAsia"), MONO)
        r.font.size = Pt(size)
    doc.add_paragraph().paragraph_format.first_line_indent = Cm(0)


def toc(doc):
    p = doc.add_paragraph()
    p.paragraph_format.first_line_indent = Cm(0)
    run = p.add_run()
    begin = OxmlElement("w:fldChar"); begin.set(qn("w:fldCharType"), "begin")
    instr = OxmlElement("w:instrText"); instr.set(qn("xml:space"), "preserve")
    # уровни 1–2 (без подпунктов вида 1.7.1) — компактное оглавление
    instr.text = r'TOC \o "1-2" \h \z \u'
    sep = OxmlElement("w:fldChar"); sep.set(qn("w:fldCharType"), "separate")
    txt = OxmlElement("w:t")
    txt.text = "Оглавление формируется автоматически: ПКМ по полю → «Обновить поле»."
    end = OxmlElement("w:fldChar"); end.set(qn("w:fldCharType"), "end")
    for el in (begin, instr, sep, txt, end):
        run._r.append(el)


