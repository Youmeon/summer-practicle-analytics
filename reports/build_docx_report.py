def pyfunc(relpath: str, *names: str) -> str:
    src = (ROOT / relpath).read_text(encoding="utf-8").splitlines()
    out = []
    for name in names:
        start = None
        for i, ln in enumerate(src):
            if re.match(rf"^\s*def {re.escape(name)}\(", ln):
                start = i
                break
        if start is None:
            log.warning("функция %s не найдена в %s", name, relpath)
            continue
        base = len(src[start]) - len(src[start].lstrip())
        end = start + 1
        while end < len(src):
            ln = src[end]
            if ln.strip() and (len(ln) - len(ln.lstrip())) <= base:
                break
            end += 1
        out.append("\n".join(src[start:end]).rstrip())
    return "\n\n".join(out)


def textslice(relpath: str, start_sub: str, end_sub: str | None = None,
              max_lines: int = 400) -> str:
    lines = (ROOT / relpath).read_text(encoding="utf-8").splitlines()
    s = next((i for i, l in enumerate(lines) if start_sub in l), 0)
    if end_sub:
        e = next((i for i, l in enumerate(lines[s + 1:], s + 1) if end_sub in l),
                 len(lines))
    else:
        e = min(len(lines), s + max_lines)
    return "\n".join(lines[s:e]).rstrip()


def _sql_table(relpath: str, tbl: str) -> str:
    """Полное определение CREATE TABLE <tbl> ( ... ) ...;  из .sql-файла."""
    lines = (ROOT / relpath).read_text(encoding="utf-8").splitlines()
    s = next(i for i, l in enumerate(lines) if l.strip().startswith(
        f"CREATE TABLE {tbl} "))
    e = s
    while e < len(lines) and not lines[e].rstrip().endswith(";"):
        e += 1
    return "\n".join(lines[s:e + 1])


