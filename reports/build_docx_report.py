def draw_schema() -> None:
    out = FIGURES_DIR / "er_schema.png"
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.patches import FancyBboxPatch

    boxes = {
        "fact_sales\n\nsales_key (PK)\ndate_key (FK)\ncustomer_key (FK)\n"
        "product_key (FK)\ncountry_key (FK)\ninvoice_no, invoice_ts\n"
        "quantity, unit_price\ngross_amount, is_return": (0.5, 0.5, "#dbeafe"),
        "dim_date\n\ndate_key (PK)\nfull_date, year, quarter\nmonth, ym, week_iso\n"
        "day_of_week, is_weekend": (0.5, 0.90, "#dcfce7"),
        "dim_customer\n\ncustomer_key (PK)\ncustomer_id\ncountry, is_guest\n"
        "first/last_order_date\norders_count": (0.11, 0.5, "#dcfce7"),
        "dim_product\n\nproduct_key (PK)\nstock_code (UK)\ndescription\ncategory\n"
        "is_service": (0.89, 0.5, "#dcfce7"),
        "dim_country\n\ncountry_key (PK)\ncountry_name (UK)\nregion": (0.5, 0.12, "#dcfce7"),
    }
    fig, ax = plt.subplots(figsize=(11, 8))
    ax.set_xlim(0, 1); ax.set_ylim(0, 1); ax.axis("off")
    fact = next(t for t in boxes if t.startswith("fact_sales"))
    fx, fy, _ = boxes[fact]
    for text, (x, y, _c) in boxes.items():
        if text is fact:
            continue
        if abs(x - fx) > abs(y - fy):
            x0 = fx + (0.15 if x > fx else -0.15); x1 = x + (-0.10 if x > fx else 0.10)
            ax.plot([x0, x1], [fy, y], color="#94a3b8", lw=1.3, zorder=1)
        else:
            y0 = fy + (0.17 if y > fy else -0.17); y1 = y + (-0.12 if y > fy else 0.12)
            ax.plot([fx, x], [y0, y1], color="#94a3b8", lw=1.3, zorder=1)
    for text, (x, y, color) in boxes.items():
        w, hh = (0.30, 0.34) if text.startswith("fact_sales") else (0.20, 0.24)
        ax.add_patch(FancyBboxPatch((x - w / 2, y - hh / 2), w, hh,
                     boxstyle="round,pad=0.012", fc=color, ec="#334155", lw=1.4,
                     zorder=2))
        ax.text(x, y, text, ha="center", va="center", fontsize=8.2,
                family="DejaVu Sans", zorder=3)
    ax.set_title("Схема базы данных retail_dwh — модель «звезда»",
                 fontsize=12, family="DejaVu Sans")
    fig.savefig(out, dpi=150, bbox_inches="tight")
    plt.close(fig)
    log.info("схема БД → %s", out.name)


